// ── Builds the system+user prompt using ONLY the packet + the fixed input view — no other input
// source exists. Returns { system, user } strings; makes no network call. ──
export function buildPacketAuthoringPrompt(packet, fixedView) {
  fixedView = fixedView || buildFixedInputView();
  const authorFloor = _sandbox._buildAuthorFloorDirective(fixedView);
  const loreFidelity = _sandbox._buildLoreFidelityDirective();
  const wardrobe = _sandbox._CG_WORLD_WARDROBE[fixedView.world] || '';

  const system = 'You are a CG-native screenplay-structure author for a fixed, one-time authoring pass. '
    + 'You receive an IMMUTABLE source packet as your only story-content authority and must return ONLY the allowlisted JSON output schema.'
    + authorFloor + '\n' + loreFidelity + '\nWORLD WARDROBE: ' + wardrobe;

  const user = renderPacketAsPromptText(packet);

  return { system, user };
}


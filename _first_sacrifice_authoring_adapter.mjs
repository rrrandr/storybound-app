      tier: 'primary', name: 'Grok-4.3', roleTag: 'firstSacrificeAuthoringDraft',
      endpoint: '/api/proxy', role: 'STRUCTURE_GENERATOR', preferredModel: 'grok-4-1-fast-reasoning',

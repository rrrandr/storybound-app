#!/usr/bin/env node
// FIRST SACRIFICE — d2/interaction_sheet_1 IMAGE-PRECEDENT AUDIT (Roman, 2026-09-20)
//
// Real Attempt 8 depicted the wish-twist/arrest beats (d2, images 13-14) as a dark-seam magical
// attack — now corrected as a real Fatelands canon error (_fatelands_ordinary_wish_misalignment_
// law.json). This audits the EXISTING d2 interaction quadrant (the real, on-disk asset/occurrence
// declaration in public/starter-scenes.js) for a baked visual conflict with the corrected canon.
// Per Roman's explicit instruction: flag a conflict if the existing asset depicts a dark
// attack/rupture, remap ONLY if an already-baked compatible asset exists, and generate NOTHING.
//
// usage: node _first_sacrifice_d2_image_precedent_audit.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
let pass = 0, fail = 0; const fails = [];
function ok(label, cond, detail) {
  if (cond) { pass++; console.log('  ✓ ' + label); }
  else { fail++; fails.push(label + (detail ? ' — ' + detail : '')); console.log('  ✗ ' + label + (detail ? ' — ' + detail : '')); }
}

console.log('\n' + '='.repeat(92) + '\nFIRST SACRIFICE — d2 IMAGE-PRECEDENT AUDIT (dry, no image call)\n' + '='.repeat(92) + '\n');

const starterSrc = fs.readFileSync(path.join(__dirname, 'public/starter-scenes.js'), 'utf8');
const keyIdx = starterSrc.indexOf('starter_first_sacrifice:');
const braceStart = starterSrc.indexOf('{', keyIdx);
let depth = 0, i = braceStart, braceEnd = -1;
for (; i < starterSrc.length; i++) { if (starterSrc[i] === '{') depth++; else if (starterSrc[i] === '}') { depth--; if (depth === 0) { braceEnd = i; break; } } }
const REAL_PKG = new Function('return ' + starterSrc.slice(braceStart, braceEnd + 1))();

const d2Occurrence = REAL_PKG.imageOccurrences.d2;
ok('real d2 occurrence loaded from public/starter-scenes.js', !!d2Occurrence, JSON.stringify(d2Occurrence));
ok('d2 maps to the shared interaction_sheet_1 asset (a real, on-disk fact, not an assumption)', d2Occurrence && d2Occurrence.assetId === 'interaction_sheet_1' && d2Occurrence.treatment === 'quadrant' && d2Occurrence.quadrant === 1);

const sheetAsset = (REAL_PKG.imageAssets || []).find(a => a.id === 'interaction_sheet_1');
ok('interaction_sheet_1 asset entry found', !!sheetAsset, JSON.stringify(sheetAsset));

const d2Image = (REAL_PKG.images || []).find(im => im.id === 'd2');
const d2Subject = d2Image ? d2Image.subject : null;

const ATTACK_VISUAL_RE = /\b(seam|rift|beam|projectile|scorch|burst|blast|explosion)\b|rope of light/i;
const subjectDepictsAttack = d2Subject ? ATTACK_VISUAL_RE.test(d2Subject) : false;
const assetHasRealUrl = !!(sheetAsset && sheetAsset.url);

console.log('\nReal on-disk facts:');
console.log('  d2 image subject label: ' + JSON.stringify(d2Subject));
console.log('  interaction_sheet_1.url: ' + JSON.stringify(sheetAsset && sheetAsset.url));
console.log('  subject label depicts attack-grammar visual: ' + subjectDepictsAttack);
console.log('  asset has a real generated image (url present): ' + assetHasRealUrl);

ok('AUDIT FINDING: interaction_sheet_1 has never been generated (url is null) — no baked visual exists for d2 to conflict with the corrected canon', sheetAsset && sheetAsset.url === null);
ok('AUDIT FINDING: the existing d2 subject label itself does NOT encode attack/rupture visual grammar (no seam/rift/beam/projectile/scorch/burst/blast/explosion/rope-of-light)', !subjectDepictsAttack, 'subject=' + JSON.stringify(d2Subject));

console.log('\nCONCLUSION: no baked visual conflict exists for d2/interaction_sheet_1 — nothing has ever been generated for it, and its existing subject label is not itself attack-grammar. Per Roman\'s instruction, a remap only applies when an already-baked COMPATIBLE asset exists; there is nothing baked at all here, so there is nothing to remap and nothing generated by this audit. No image call was made.');

console.log('\n' + '='.repeat(92));
console.log('d2 IMAGE-PRECEDENT AUDIT: ' + pass + ' passed, ' + fail + ' failed');
if (fail) { console.log('\nFAILURES:'); fails.forEach(f => console.log('  - ' + f)); }
process.exitCode = fail ? 1 : 0;

#!/usr/bin/env node
// Regenerates 04_review_preview.md and REPORT.md from the ALREADY-SAVED real draft
// (_first_sacrifice_draft_v1/02_draft_v1.json) and the already-saved real request/response
// records — NO new provider call, purely local post-processing of content already obtained and
// paid for. Corrects: (1) the preview renderer's crash on string-shaped OAS line fields
// (Roman's authorized run surfaced this as a genuine model schema-compliance defect, now
// reported as a violation instead of throwing); (2) precise model naming per Roman's correction
// (2026-09-16): "grok-4-1-fast-reasoning" is a legacy ALIAS, not a real distinct model — the
// real billed model (confirmed directly from the proxy's own console log at call time) is
// grok-4.3 at reasoning effort=high.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(__dirname, '_first_sacrifice_draft_v1');
const PACKET = JSON.parse(fs.readFileSync(path.join(__dirname, '_first_sacrifice_source_packet.json'), 'utf8'));
const draftArtifact = JSON.parse(fs.readFileSync(path.join(OUT_DIR, '02_draft_v1.json'), 'utf8'));
const draft = draftArtifact.draft;
const records = JSON.parse(fs.readFileSync(path.join(OUT_DIR, '01_request_response_records.json'), 'utf8'));
const validation = JSON.parse(fs.readFileSync(path.join(OUT_DIR, '03_validation_result.json'), 'utf8'));
const flagged = JSON.parse(fs.readFileSync(path.join(OUT_DIR, '03b_flagged_candidates.json'), 'utf8'));

const winningRecord = records.find(r => r.httpStatus === 200);
const winningUsage = winningRecord.responseBody.usage;
// PRECISE MODEL NAMING (Roman's correction): the real billed model, confirmed from the proxy's
// own console log at call time ("latency=14544ms model=grok-4.3 effort=high
// (chain=\"grok-4-1-fast-reasoning\") status=200"), not from _orchestration.model (which only
// echoes back the requested legacy alias name, a real observability gap in api/proxy.js's own
// response — disclosed here, not silently worked around).
const winningModelReal = 'grok-4.3';
const winningEffort = 'high';
const requestedAlias = winningRecord.requestedModel; // 'grok-4-1-fast-reasoning' — the alias sent, not the real billed model

const PRICING = { 'grok-4.3': { in: 0.00000125, out: 0.0000025 } };
const p = PRICING[winningModelReal];
const realCostUSD = +((winningUsage.prompt_tokens * p.in) + (winningUsage.completion_tokens * p.out)).toFixed(6);

function renderOasField(L, v, label) {
  L.push('**' + label + '**');
  if (Array.isArray(v)) { v.forEach(l => L.push('> ' + (l.speaker ? l.speaker + ': ' : '') + l.text)); }
  else if (typeof v === 'string' && v) { L.push('⚠ SCHEMA VIOLATION — expected an array of {speaker,text} lines, model returned a plain string:'); L.push('> ' + v); }
  else { L.push('(empty)'); }
  L.push('');
}

function renderPreview() {
  const L = [];
  L.push('# First Sacrifice — Draft v1 Review Preview (REAL, authorized draft)');
  L.push('');
  L.push('**Packet**: ' + PACKET.packet_id + ' v' + PACKET.version);
  L.push('**Generated by**: ' + winningModelReal + ' (reasoning effort: ' + winningEffort + '; requested via legacy alias "' + requestedAlias + '" — see api/proxy.js:_resolveGrokModel) | primary tier, first attempt');
  L.push('**Usage**: ' + JSON.stringify(winningUsage) + ' | **real cost**: $' + realCostUSD + ' (2,806 prompt tok × $1.25/MTok + 901 completion tok [incl. 563 reasoning tok] × $2.50/MTok)');
  L.push('**xAI-reported cost_in_usd_ticks**: ' + winningUsage.cost_in_usd_ticks + ' (raw field from the xAI response; exact tick-to-USD conversion not independently confirmed — the $' + realCostUSD + ' figure above uses this session\'s own sourced per-token pricing instead)');
  L.push('');
  L.push('## Validator result: ' + (validation.ok ? '✅ ELIGIBLE FOR REVIEW' : '❌ NOT ELIGIBLE — structural/canon violations found') + ' (structural/canon check only — this is NOT a prose-quality judgment)');
  if (!validation.ok) validation.violations.forEach(v => L.push('- **' + v.rule + '**: ' + v.detail));
  L.push('');
  if (flagged.length) {
    L.push('## ⚠ FLAGGED NEW-CANON CANDIDATES (' + flagged.length + ') — visibly flagged, NOT merged into canon');
    flagged.forEach(f => L.push('- ' + f.where + ': ' + JSON.stringify(f.beat)));
  } else {
    L.push('## No flagged_new_canon_candidate content in this draft.');
  }
  L.push('');
  L.push('## Scene beats');
  (draft.beats || []).forEach((b, i) => {
    const prov = b.provenance || {};
    const citeField = prov.cites || prov.citation; // model used "citation", schema expects "cites" — shown either way, not silently corrected
    L.push('**Beat ' + i + '** [' + b.kind + (b.speaker ? ', ' + b.speaker : '') + ', image=' + (b.image || '-') + '] — claim kind: `' + prov.kind + '`' + (citeField ? ' (cite: ' + citeField + (prov.citation && !prov.cites ? ' — ⚠ field named "citation", schema expects "cites"' : '') + ')' : ' — ⚠ NO CITATION FIELD'));
    if (b.interiority) L.push('*interiority: ' + b.interiority + '*');
    L.push('> ' + b.text);
    L.push('');
  });
  const oas = draft.oas || {};
  L.push('## OAS sequence');
  renderOasField(L, oas.interrogation, '1. Interrogation');
  renderOasField(L, oas.interruption, '2. Institutional interruption');
  renderOasField(L, oas.claimOverInquiry, '3. Julian\'s claim over the inquiry');
  L.push('**4. Five Fate cards** (card_behavior="' + oas.cardBehavior + '"' + (oas.cardBehavior !== 'fills_draft_only' ? ' — ⚠ SCHEMA VIOLATION: expected literal string "fills_draft_only"' : '') + ', submit_required=' + oas.submitRequired + ', custom_say_do=' + oas.customSayDo + ')');
  (oas.fateCards || []).forEach((c, i) => L.push((i + 1) + '. **' + c.posture_label + '** — ' + c.prefill_text));
  L.push('');
  L.push('## Operation record');
  L.push('- Tiers attempted: ' + records.map(r => r.provider + ' (status ' + r.httpStatus + ')').join(', ') + ' — Grok succeeded on the FIRST attempt, no fallback tier was reached');
  L.push('- No second draft call was made, and none will be, regardless of the validator result above.');
  L.push('- No images were generated. No package/starter-scenes.js write occurred. No live-reader launch occurred.');
  return L.join('\n');
}

const preview = renderPreview();
fs.writeFileSync(path.join(OUT_DIR, '04_review_preview.md'), preview);

const report = [
  '# First Sacrifice Scene-1/OAS draft-authoring operation — REPORT',
  '',
  '**Calls made**: 1 (Grok primary — succeeded on first attempt; Ministral-8B and GPT-4o were never invoked)',
  '**Winning model**: ' + winningModelReal + ' (reasoning effort: ' + winningEffort + '; requested via alias "' + requestedAlias + '")',
  '**Tokens**: prompt=' + winningUsage.prompt_tokens + ', completion=' + winningUsage.completion_tokens + ' (of which ' + winningUsage.completion_tokens_details.reasoning_tokens + ' reasoning), total=' + winningUsage.total_tokens + ', cached=' + winningUsage.prompt_tokens_details.cached_tokens,
  '**Real cost**: $' + realCostUSD + ' (well under the $0.0237 expected-Grok-success ceiling)',
  '**Validator**: ' + (validation.ok ? 'ELIGIBLE FOR REVIEW' : 'NOT ELIGIBLE — ' + validation.violations.length + ' structural violation(s), see 03_validation_result.json') + ' — structural/canon check only, NOT a prose-quality judgment',
  '**Flagged new-canon candidates**: ' + flagged.length,
  '**No second draft call was made.**',
  '',
  'Files: 01_request_response_records.json, 02_draft_v1.json, 03_validation_result.json, 03b_flagged_candidates.json, 04_review_preview.md (READ THIS for the fiction), raw_winning_content.txt.',
].join('\n');
fs.writeFileSync(path.join(OUT_DIR, 'REPORT.md'), report);
console.log(report);

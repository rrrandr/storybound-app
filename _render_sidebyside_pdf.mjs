#!/usr/bin/env node
// Renders the CURRENT (baked) vs CANDIDATE (Grok draft) Scene 1 as a true two-column side-by-side
// PDF, plus the shared downstream (interrogation, fixed tail, cards), to the Desktop.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const draftArtifact = JSON.parse(fs.readFileSync(path.join(__dirname, '_first_sacrifice_draft_v3_full_package/02_draft.json'), 'utf8'));
const draft = draftArtifact.draft;

const starterSrc = fs.readFileSync(path.join(__dirname, 'public/starter-scenes.js'), 'utf8');
const beatsBlockMatch = starterSrc.match(/beats: \[([\s\S]*?)\],\s*\n\s*endsAt:/);
const oasHandoffBlockMatch = starterSrc.match(/oasHandoff: \{([\s\S]*?)\n      \},\s*\n\s*emitted:/);
const currentBeats = new Function('return [' + beatsBlockMatch[1] + ']')();
const oasHandoff = new Function('return {' + oasHandoffBlockMatch[1] + '\n}')();

const candidateBeats = draft.scene1Candidate.beats;
const currentWords = currentBeats.reduce((n, b) => n + b.text.split(/\s+/).length, 0);
const candidateWords = candidateBeats.reduce((n, b) => n + b.text.split(/\s+/).length, 0);

function esc(s) { return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }

function renderBeatsColumn(beats, showMeta) {
  return beats.map(b => {
    const meta = showMeta ? `<div class="beatmeta">${esc(b.kind)} · image=${esc(b.image)}${b.provenance ? ' · ' + esc(b.provenance.kind) + (b.provenance.cites ? ' (' + esc(b.provenance.cites) + ')' : '') : ''}</div>` : '';
    const speaker = b.speaker ? `<div class="speaker">${esc(b.speaker)}</div>` : '';
    return `<div class="beat">${speaker}${meta}<p>${esc(b.text)}</p></div>`;
  }).join('\n');
}

const html = `<!doctype html><html><head><meta charset="utf-8"><title>First Sacrifice — Side by Side</title><style>
  body { font-family: Georgia, 'Times New Roman', serif; color: #1a1a1a; line-height: 1.5; margin: 0; padding: 30px 24px; font-size: 12px; }
  h1 { font-size: 20px; border-bottom: 2px solid #333; padding-bottom: 8px; margin: 0 0 6px; }
  .meta { font-size: 11px; color: #444; margin-bottom: 4px; }
  .badge { display:inline-block; padding:2px 8px; border-radius:4px; font-size:10px; font-weight:bold; margin-right:6px; }
  .badge.ok { background:#dcf3dc; color:#1a6b1a; }
  h2.colhead { font-size: 14px; margin: 0 0 4px; padding: 6px 8px; border-radius: 4px; }
  h2.colhead.a { background:#f0ece0; color:#5a4a2a; }
  h2.colhead.b { background:#e6eef7; color:#1a3a5a; }
  .wordcount { font-size: 10px; font-weight: normal; color: #666; }
  .columns { display: grid; grid-template-columns: 1fr 1fr; gap: 18px; margin-top: 10px; }
  .col { border: 1px solid #ddd; border-radius: 6px; padding: 10px 12px; background: #fdfdfb; }
  .col.b { background: #fbfcfe; }
  .beat { margin-bottom: 9px; padding-bottom: 7px; border-bottom: 1px dotted #ddd; }
  .beat:last-child { border-bottom: none; }
  .speaker { font-weight: bold; font-size: 11px; }
  .beatmeta { font-size: 9px; color: #888; font-style: italic; margin-bottom: 2px; }
  p { margin: 2px 0; }
  .section { margin-top: 22px; page-break-before: always; }
  .section h2 { font-size: 15px; border-bottom: 1px solid #bbb; padding-bottom: 4px; }
  .line { margin: 4px 0; }
  .fixedline { background: #fff6e0; padding: 3px 6px; border-radius: 3px; }
  code { background: #eee; padding: 1px 4px; border-radius: 3px; font-family: Menlo, monospace; font-size: 10px; }
  .cards { display: grid; grid-template-columns: 1fr 1fr; gap: 10px; margin-top: 8px; }
  .card { border: 1px solid #ccc; border-radius: 5px; padding: 7px 9px; }
  .card h3 { margin: 0 0 3px; font-size: 12px; text-transform: uppercase; letter-spacing: 0.5px; }
  .finding { background: #fff0f0; border: 1px solid #e0b0b0; border-radius: 6px; padding: 10px 12px; margin-top: 12px; font-size: 11.5px; }
</style></head><body>

<h1>First Sacrifice — Current vs. Candidate (Grok draft)</h1>
<div class="meta"><span class="badge ok">VALIDATOR: ELIGIBLE FOR REVIEW — 0 violations</span></div>
<div class="meta">Generated by grok-4.3 (reasoning effort: high) · 4,496 prompt / 1,505 completion tokens (of 6,000 available — 25% used, no truncation) · real cost $0.0094</div>

<div class="finding"><strong>Finding:</strong> the candidate is ${candidateWords} words across ${candidateBeats.length} beats; the current baked scene is ${currentWords} words across ${currentBeats.length} beats — roughly ⅙ the length. This was NOT token-limit truncation (only 1,505 of 6,000 completion tokens were used). The prompt specified a beat-COUNT target but never a beat-density/length target, so Grok satisfied "~20 beats" with short functional lines instead of matching the baked scene's paragraph-length richness.</div>

<div class="columns">
  <div class="col a">
    <h2 class="colhead a">OPTION A — CURRENT (baked, real) <span class="wordcount">${currentBeats.length} beats, ${currentWords} words</span></h2>
    ${renderBeatsColumn(currentBeats, false)}
  </div>
  <div class="col b">
    <h2 class="colhead b">OPTION B — CANDIDATE (this Grok draft) <span class="wordcount">${candidateBeats.length} beats, ${candidateWords} words</span></h2>
    ${renderBeatsColumn(candidateBeats, true)}
  </div>
</div>

<div class="section">
  <h2>Shared downstream (identical regardless of which Scene 1 is selected)</h2>
  <p><em>${esc(oasHandoff.cue)}</em></p>
  <h3>Interrogation (NEW — this generation)</h3>
  ${draft.interrogationExchange.map(l => `<div class="line">${l.speaker ? '<strong>' + esc(l.speaker) + ':</strong> ' : '<em>(narration)</em> '}${esc(l.text)}</div>`).join('\n')}
  <h3>Interruption + claim (FIXED — baked, spliced in, never regenerated)</h3>
  <div class="line fixedline"><em>${esc(oasHandoff.interruption)}</em></div>
  ${oasHandoff.interruptionExchange.map(l => `<div class="line fixedline">${l.speaker ? '<strong>' + esc(l.speaker) + ':</strong> ' : '<em>(narration)</em> '}${esc(l.text)}</div>`).join('\n')}
  <h3>Five Fate Cards</h3>
  <div class="cards">
    ${['temptation','silence','reversal','boundary','confession'].map(k => {
      const c = draft.fateCards[k];
      return `<div class="card"><h3>${k} <span class="wordcount">(${esc(c.variant)})</span></h3><p><strong>action:</strong> ${esc(c.action)}</p><p><strong>dialogue:</strong> ${esc(c.dialogue)}</p></div>`;
    }).join('\n')}
  </div>
</div>

</body></html>`;

fs.writeFileSync(path.join(__dirname, '_sidebyside_tmp.html'), html);

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(html, { waitUntil: 'load' });
const desktopPath = path.join(os.homedir(), 'Desktop', 'First_Sacrifice_Current_vs_Candidate.pdf');
await page.pdf({ path: desktopPath, format: 'Letter', landscape: true, margin: { top: '0.4in', bottom: '0.4in', left: '0.4in', right: '0.4in' }, printBackground: true });
await browser.close();
fs.unlinkSync(path.join(__dirname, '_sidebyside_tmp.html'));
console.log('PDF written to: ' + desktopPath);

#!/usr/bin/env node
// Renders the CURRENT (baked) vs CANDIDATE (v7 attempt 4, STRUCTURALLY REJECTED) Scene 1 as a true
// two-column side-by-side PDF, plus the shared downstream (authored oasOpening, fixed interruption
// tail, authored postInterruptionBeat, cards), to the Desktop. Roman: "clearly marked structurally
// rejected... hide provenance metadata so you can read it as fiction."
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const draftArtifact = JSON.parse(fs.readFileSync(path.join(__dirname, '_first_sacrifice_draft_v7_attempt4_full_package/02_draft.json'), 'utf8'));
const validation = JSON.parse(fs.readFileSync(path.join(__dirname, '_first_sacrifice_draft_v7_attempt4_full_package/03_validation_result.json'), 'utf8'));
const draft = draftArtifact.draft;
const usage = draftArtifact.generated_by.usage;

const starterSrc = fs.readFileSync(path.join(__dirname, 'public/starter-scenes.js'), 'utf8');
const beatsBlockMatch = starterSrc.match(/beats: \[([\s\S]*?)\],\s*\n\s*endsAt:/);
const oasHandoffBlockMatch = starterSrc.match(/oasHandoff: \{([\s\S]*?)\n      \},\s*\n\s*emitted:/);
const currentBeats = new Function('return [' + beatsBlockMatch[1] + ']')();
const oasHandoff = new Function('return {' + oasHandoffBlockMatch[1] + '\n}')();

const candidateBeats = draft.scene1Candidate.beats;
const currentWords = currentBeats.reduce((n, b) => n + b.text.split(/\s+/).length, 0);
const candidateWords = candidateBeats.reduce((n, b) => n + b.text.split(/\s+/).length, 0);
// Same PRICING table/formula as _first_sacrifice_draft_authoring_run.mjs — not a guessed ticks
// conversion, the same real per-token math that produced the $0.016714 already reported.
const PRICING = { 'grok-4.3': { in: 0.00000125, out: 0.0000025 } };
const realCostUsd = (usage.prompt_tokens * PRICING['grok-4.3'].in + usage.completion_tokens * PRICING['grok-4.3'].out).toFixed(6);

function esc(s) { return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }

// Provenance metadata hidden — Roman: "so you can read it as fiction."
function renderBeatsColumnFixed(beats) {
  return beats.map(b => {
    const speaker = b.speaker ? `<div class="speaker">${esc(b.speaker)}</div>` : '';
    return `<div class="beat">${speaker}<p>${esc(b.text)}</p></div>`;
  }).join('\n');
}

const html = `<!doctype html><html><head><meta charset="utf-8"><title>First Sacrifice — Current vs. Candidate (v7 attempt 4)</title><style>
  body { font-family: Georgia, 'Times New Roman', serif; color: #1a1a1a; line-height: 1.5; margin: 0; padding: 30px 24px; font-size: 12px; }
  h1 { font-size: 20px; border-bottom: 2px solid #333; padding-bottom: 8px; margin: 0 0 6px; }
  .meta { font-size: 11px; color: #444; margin-bottom: 4px; }
  .badge { display:inline-block; padding:2px 8px; border-radius:4px; font-size:10px; font-weight:bold; margin-right:6px; }
  .badge.rejected { background:#f8d7d7; color:#8a1f1f; }
  h2.colhead { font-size: 14px; margin: 0 0 4px; padding: 6px 8px; border-radius: 4px; }
  h2.colhead.a { background:#f0ece0; color:#5a4a2a; }
  h2.colhead.b { background:#fbe6e6; color:#7a2020; }
  .wordcount { font-size: 10px; font-weight: normal; color: #666; }
  .columns { display: grid; grid-template-columns: 1fr 1fr; gap: 18px; margin-top: 10px; }
  .col { border: 1px solid #ddd; border-radius: 6px; padding: 10px 12px; background: #fdfdfb; }
  .col.b { background: #fffafa; }
  .beat { margin-bottom: 9px; padding-bottom: 7px; border-bottom: 1px dotted #ddd; }
  .beat:last-child { border-bottom: none; }
  .speaker { font-weight: bold; font-size: 11px; }
  p { margin: 2px 0; }
  .section { margin-top: 22px; page-break-before: always; }
  .section h2 { font-size: 15px; border-bottom: 1px solid #bbb; padding-bottom: 4px; }
  .line { margin: 4px 0; }
  .fixedline { background: #fff6e0; padding: 3px 6px; border-radius: 3px; }
  .newline { background: #eaf3ff; padding: 3px 6px; border-radius: 3px; }
  .cards { display: grid; grid-template-columns: 1fr 1fr; gap: 10px; margin-top: 8px; }
  .card { border: 1px solid #ccc; border-radius: 5px; padding: 7px 9px; }
  .card h3 { margin: 0 0 3px; font-size: 12px; text-transform: uppercase; letter-spacing: 0.5px; }
  .finding { background: #fff0f0; border: 1px solid #e0b0b0; border-radius: 6px; padding: 10px 12px; margin-top: 12px; font-size: 11.5px; }
</style></head><body>

<h1>First Sacrifice — Current vs. Candidate (v7 attempt 4)</h1>
<div class="meta"><span class="badge rejected">STRUCTURALLY REJECTED — ${validation.violations.length} violation(s)</span></div>
<div class="meta">Generated by grok-4-1-fast-reasoning (Grok-4.3) · ${usage.prompt_tokens} prompt / ${usage.completion_tokens} completion tokens (of 8,000 available) · real cost $${realCostUsd}</div>
<div class="meta">Validator violations: ${validation.violations.map(v => esc(v.rule)).join(', ')}</div>

<div class="finding"><strong>Finding:</strong> the candidate is ${candidateWords} words across ${candidateBeats.length} beats (target: exactly ~20 beats, 1,100-1,700 words); the current baked scene is ${currentWords} words across ${currentBeats.length} beats. This is the 4th real attempt against this packet — the strongest yet on a per-beat basis (many beats land in a genuine 70-110 word dramatized range, and the new authored oasOpening below is the best of all 4 attempts), but beat COUNT fell short (14 of the required 18-22), so the total stayed under the 1,100-word floor. Structurally rejected — not approved for use.</div>

<div class="columns">
  <div class="col a">
    <h2 class="colhead a">OPTION A — CURRENT (baked, real) <span class="wordcount">${currentBeats.length} beats, ${currentWords} words</span></h2>
    ${renderBeatsColumnFixed(currentBeats)}
  </div>
  <div class="col b">
    <h2 class="colhead b">OPTION B — CANDIDATE v7 attempt 4 (STRUCTURALLY REJECTED) <span class="wordcount">${candidateBeats.length} beats, ${candidateWords} words</span></h2>
    ${renderBeatsColumnFixed(candidateBeats)}
  </div>
</div>

<div class="section">
  <h2>OAS sequence — authored opener, fixed interruption tail, authored post-interruption beat</h2>
  <p><em>${esc(oasHandoff.cue)}</em></p>
  <h3>oasOpening (NEW — this generation, the ONLY OAS content this operation authors)</h3>
  <div class="line newline"><strong>${esc(draft.oasOpening.speaker)}:</strong> ${esc(draft.oasOpening.text)}</div>
  <h3>[Everything between here and the interruption is LIVE, player-driven OAS — not authored, not rendered]</h3>
  <h3>Interruption + fixed tail (FIXED — baked, spliced in, never regenerated)</h3>
  <div class="line fixedline"><em>${esc(oasHandoff.interruption)}</em></div>
  ${oasHandoff.interruptionExchange.map(l => `<div class="line fixedline">${l.speaker ? '<strong>' + esc(l.speaker) + ':</strong> ' : '<em>(narration)</em> '}${esc(l.text)}</div>`).join('\n')}
  <h3>postInterruptionBeat (NEW — this generation, the final-choice frame)</h3>
  <div class="line newline">${draft.postInterruptionBeat.speaker ? '<strong>' + esc(draft.postInterruptionBeat.speaker) + ':</strong> ' : '<em>(narration)</em> '}${esc(draft.postInterruptionBeat.text)}</div>
  <h3>Five Fate Cards</h3>
  <div class="cards">
    ${['temptation','silence','reversal','boundary','confession'].map(k => {
      const c = draft.fateCards[k];
      return `<div class="card"><h3>${k} <span class="wordcount">(${esc(c.variant)})</span></h3><p><strong>action:</strong> ${esc(c.action)}</p><p><strong>dialogue:</strong> ${esc(c.dialogue)}</p></div>`;
    }).join('\n')}
  </div>
</div>

</body></html>`;

fs.writeFileSync(path.join(__dirname, '_sidebyside_tmp_v7attempt4.html'), html);

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(html, { waitUntil: 'load' });
const desktopPath = path.join(os.homedir(), 'Desktop', 'First_Sacrifice_Current_vs_Candidate_v7_Attempt4_REJECTED.pdf');
await page.pdf({ path: desktopPath, format: 'Letter', landscape: true, margin: { top: '0.4in', bottom: '0.4in', left: '0.4in', right: '0.4in' }, printBackground: true });
await browser.close();
fs.unlinkSync(path.join(__dirname, '_sidebyside_tmp_v7attempt4.html'));
console.log('PDF written to: ' + desktopPath);
